def sample_signature(expr, variables):
    vals = (ZERO, ONE, Succ(ONE))
    out = []
    from itertools import product
    for combo in product(vals, repeat=len(variables)):
        grounded = expr
        for var, value in zip(variables, combo):
            grounded = substitute_expr(grounded, var, value)
        try:
            normal, _ = normalize(grounded, max_steps=2000)
            out.append(str(normal))
        except RuntimeError:
            out.append("<normalization-failed>")
    return tuple(out)


def main():
    state = build_initial_knowledge()
    selector = StrategySelector()
    families = candidate_specs()
    assert len(families) == 5
    assert all(len(items) == 20 for items in families.values())

    rows = []
    for parent, specs in families.items():
        for idx, (left, right, variables) in enumerate(specs, 1):
            conjecture = close_eq(left, right, variables)
            sample_pass = sample_signature(left, variables) == sample_signature(right, variables)
            assessment = assess_research_value(conjecture, state, frontier=())
            result = selector.solve(conjecture, state, lemma_budget=0)
            proved = bool(result.found and result.check and result.check.valid)
            rows.append({
                "parent": parent,
                "index": idx,
                "statement": str(conjecture.statement),
                "sample_pass": sample_pass,
                "value": assessment.score,
                "accepted": assessment.accepted,
                "reason": assessment.reason,
                "proved": proved,
                "strategy": result.strategy,
            })

    counts = Counter()
    for r in rows:
        counts["total"] += 1
        counts["sample_pass"] += int(r["sample_pass"])
        counts["sample_fail"] += int(not r["sample_pass"])
        counts["research_accepted"] += int(r["accepted"])
        counts["research_rejected"] += int(not r["accepted"])
        counts["proved"] += int(r["proved"])
        counts["unproved"] += int(not r["proved"])
        counts["proved_and_accepted"] += int(r["proved"] and r["accepted"])

    print("AI_PARENT_NEIGHBORHOOD_EXPERIMENT")
    print("parents=5 candidates=100 candidates_per_parent=20")
    for key in ("total","sample_pass","sample_fail","research_accepted","research_rejected","proved","unproved","proved_and_accepted"):
        print(f"{key}={counts[key]}")

    by_parent = defaultdict(Counter)
    for r in rows:
        c = by_parent[r["parent"]]
        c["total"] += 1
        c["sample_pass"] += int(r["sample_pass"])
        c["accepted"] += int(r["accepted"])
        c["proved"] += int(r["proved"])
        c["proved_and_accepted"] += int(r["proved"] and r["accepted"])

    print("\nBY_PARENT")
    for parent, c in by_parent.items():
        print(parent, dict(c))

    print("\nTOP_RESEARCH_ACCEPTED")
    accepted = sorted((r for r in rows if r["accepted"]), key=lambda r: (-r["value"], r["parent"], r["index"]))
    for r in accepted[:20]:
        print(f'{r["parent"]}#{r["index"]:02d} value={r["value"]} proved={r["proved"]} sample={r["sample_pass"]} :: {r["statement"]}')

    print("\nPROVED_AND_ACCEPTED")
    for r in rows:
        if r["proved"] and r["accepted"]:
            print(f'{r["parent"]}#{r["index"]:02d} value={r["value"]} strategy={r["strategy"]} :: {r["statement"]}')

    print("\nUNPROVED_SAMPLE_PASS_TOP")
    pending = sorted((r for r in rows if r["sample_pass"] and not r["proved"]), key=lambda r: -r["value"])
    for r in pending[:20]:
        print(f'{r["parent"]}#{r["index"]:02d} value={r["value"]} accepted={r["accepted"]} :: {r["statement"]}')


if __name__ == "__main__":
    main()
