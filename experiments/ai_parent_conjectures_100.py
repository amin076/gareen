from research_value import assess_research_value


def add(*xs):
    out = xs[0]
    for x in xs[1:]:
        out = Add(out, x)
    return out


def mul(*xs):
    out = xs[0]
    for x in xs[1:]:
        out = Mul(out, x)
    return out


def close_eq(left, right, variables):
    body = Eq(left, right)
    statement = body
    for v in reversed(variables):
        statement = ForAll(v, statement)
    return ResearchConjecture(
        statement=statement,
        body=body,
        variables=tuple(variables),
        heuristic_score=10 + 2 * len(variables),
        evidence="AI-authored parent-neighborhood candidate; not generated by Gareen grammar.",
    )


